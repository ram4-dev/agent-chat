import { once } from 'node:events';
import { expect, test } from '@playwright/test';
import { authorizeAgent, mcpClient, openReceiver, payload } from './helpers/agent';

test('AC12: browser, SDK OAuth, MCP, live delivery, offline recovery and revocation', async ({ page, baseURL }) => {
  const origin = baseURL!;
  expect((await page.request.get('/.well-known/oauth-protected-resource')).status()).toBe(200);
  await page.goto('/');
  await page.getByLabel('Email').fill('full-loop@example.com');
  await page.getByLabel('Display name').fill('Ada');
  await page.getByLabel('Password').fill('a-sufficiently-long-password');
  await page.getByRole('button', { name: 'Create account' }).click();
  await expect(page.getByText('Signed in as Ada.')).toBeVisible();
  await page.setViewportSize({ width: 375, height: 812 });
  const agent = await authorizeAgent(page, origin);
  await page.goto('/');
  await page.getByLabel('New group name').fill('Full loop');
  await page.getByRole('button', { name: 'Create group', exact: true }).click();
  await page.getByRole('button', { name: 'Full loop', exact: true }).click();
  const groupId = await page.getByRole('region', { name: 'Chat in Full loop' }).getAttribute('data-group-id');
  await page.getByRole('button', { name: 'Add Scout to selected group', exact: true }).click();
  await expect(page.getByRole('list', { name: 'Members' })).toContainText('Scout (agent, owner: Ada)');
  await page.setViewportSize({ width: 375, height: 812 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(375);
  await page.screenshot({ path: '.local-state/s9-mobile.png', fullPage: true });
  await page.setViewportSize({ width: 1280, height: 900 });
  let client = await mcpClient(origin, agent.token);
  let receiver = await openReceiver(origin, agent.token);
  try {
    const spontaneous = { group_id: groupId, text: 'Runtime-initiated update', idempotency_key: 'runtime-first' };
    const first = payload<{ message: { id: string } }>(await client.callTool({ name: 'send_message', arguments: spontaneous }));
    const retry = payload<{ message: { id: string }; replayed: boolean }>(await client.callTool({ name: 'send_message', arguments: spontaneous }));
    expect(retry).toMatchObject({ replayed: true, message: { id: first.message.id } });
    const live = once(receiver, 'message');
    await page.getByRole('textbox', { name: 'Message', exact: true }).fill('Please review this');
    await page.getByRole('button', { name: 'Send', exact: true }).click();
    const event = JSON.parse(String((await live)[0]));
    expect(event).toMatchObject({ type: 'inbox.event', message: { text: 'Please review this' } });
    payload(await client.callTool({ name: 'ack_inbox', arguments: { event_id: event.event_id } }));
    receiver.close(); await once(receiver, 'close'); await client.close();
    await expect(page.getByText('Receiver disconnected.', { exact: false })).toBeVisible();
    await page.getByRole('textbox', { name: 'Message', exact: true }).fill('Published while runtime is stopped');
    await page.getByRole('button', { name: 'Send', exact: true }).click();
    await expect(page.getByRole('list', { name: 'Messages' })).toContainText('Published while runtime is stopped');
    const reauthorized = await authorizeAgent(page, origin, agent.agentId);
    expect(reauthorized.agentId).toBe(agent.agentId);
    client = await mcpClient(origin, reauthorized.token);
    receiver = await openReceiver(origin, reauthorized.token);
    const readInbox = async () => payload<{ events: { eventId: string; message: { text: string } }[] }>(await client.callTool({ name: 'get_inbox', arguments: {} }));
    const pending = await readInbox();
    expect(pending.events.map((e) => e.message.text)).toEqual(['Published while runtime is stopped']);
    const history = payload<{ messages: unknown[] }>(await client.callTool({ name: 'read_messages', arguments: { group_id: groupId } }));
    expect(history.messages).toHaveLength(3);
    expect((await readInbox()).events).toHaveLength(1);
    for (let i = 0; i < 2; i++) payload(await client.callTool({ name: 'ack_inbox', arguments: { event_id: pending.events[0]!.eventId } }));
    expect((await readInbox()).events).toEqual([]);
    await client.callTool({ name: 'send_message', arguments: { group_id: groupId, text: 'Reviewed by the external runtime', idempotency_key: 'reply-once' } });
    await page.goto('/');
    await page.getByRole('button', { name: 'Full loop', exact: true }).click();
    await expect(page.getByRole('list', { name: 'Messages' })).toContainText('Scout (agent of Ada): Reviewed by the external runtime');
    await expect(page.getByRole('list', { name: 'Owned agents' }).getByRole('heading', { name: 'Scout', exact: true })).toHaveCount(1);
    await page.getByRole('button', { name: 'Revoke agent Scout', exact: true }).click();
    const closed = once(receiver, 'close');
    await page.getByRole('button', { name: 'Confirm revocation', exact: true }).click();
    expect((await closed)[0]).toBe(4401);
    await expect(client.callTool({ name: 'read_messages', arguments: { group_id: groupId } })).rejects.toThrow('unauthenticated');
    await expect(mcpClient(origin, agent.token)).rejects.toThrow('unauthenticated');
    await expect(page.getByRole('list', { name: 'Messages' })).toContainText('Scout (agent of Ada)');
  } finally { receiver.terminate(); await client.close(); }
});
