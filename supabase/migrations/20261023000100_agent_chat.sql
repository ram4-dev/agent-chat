-- Private server-owned application data. Supabase Auth remains in auth.users.
CREATE SCHEMA IF NOT EXISTS agent_chat;
REVOKE ALL ON SCHEMA agent_chat FROM PUBLIC, anon, authenticated;
SET search_path = agent_chat, public;

-- 0001_initial_mvp
--
-- Greenfield MVP schema: identity, private groups, membership, messages,
-- send idempotency, agent inbox, OAuth state, and bounded security audit.
--
-- This file is immutable after merge. Corrections require a new numbered
-- migration. Timestamps are ISO-8601 UTC strings with millisecond precision.
-- Identifiers are opaque UUIDv7 values generated by the application.

-- Identity -------------------------------------------------------------------

CREATE TABLE users (
  id TEXT PRIMARY KEY,
  email TEXT NOT NULL UNIQUE CHECK (email = lower(email)),
  password_hash TEXT NOT NULL,
  display_name TEXT NOT NULL CHECK (length(trim(display_name)) > 0),
  created_at TEXT NOT NULL DEFAULT (to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'))
);

CREATE TABLE human_sessions (
  id TEXT PRIMARY KEY,
  user_id TEXT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  expires_at TEXT NOT NULL,
  revoked_at TEXT,
  created_at TEXT NOT NULL DEFAULT (to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'))
);

CREATE INDEX human_sessions_user_idx ON human_sessions (user_id);

CREATE TABLE agents (
  id TEXT PRIMARY KEY,
  owner_user_id TEXT NOT NULL REFERENCES users (id),
  name TEXT NOT NULL CHECK (length(trim(name)) > 0),
  avatar_url TEXT,
  description TEXT NOT NULL DEFAULT '',
  status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'revoked')),
  revoked_at TEXT,
  created_at TEXT NOT NULL DEFAULT (to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'))
);

CREATE INDEX agents_owner_idx ON agents (owner_user_id);

-- Agent ownership is fixed at insert time; profile fields stay editable.
CREATE FUNCTION enforce_agent_owner() RETURNS trigger LANGUAGE plpgsql SET search_path = agent_chat, pg_temp AS $$
BEGIN
  IF NEW.owner_user_id IS DISTINCT FROM OLD.owner_user_id THEN
    RAISE EXCEPTION 'agent owner is immutable';
  END IF;
  RETURN NEW;
END;
$$;
CREATE TRIGGER agents_owner_user_id_immutable BEFORE UPDATE OF owner_user_id ON agents
FOR EACH ROW EXECUTE FUNCTION enforce_agent_owner();

-- OAuth client registration --------------------------------------------------

CREATE TABLE oauth_clients (
  client_id TEXT PRIMARY KEY,
  client_name TEXT NOT NULL,
  redirect_uris TEXT NOT NULL,
  token_endpoint_auth_method TEXT NOT NULL DEFAULT 'none',
  is_public INTEGER NOT NULL DEFAULT 1 CHECK (is_public IN (0, 1)),
  metadata TEXT,
  created_at TEXT NOT NULL DEFAULT (to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'))
);

CREATE TABLE agent_connections (
  id TEXT PRIMARY KEY,
  agent_id TEXT NOT NULL REFERENCES agents (id) ON DELETE CASCADE,
  oauth_client_id TEXT NOT NULL REFERENCES oauth_clients (client_id),
  scopes TEXT NOT NULL,
  revoked_at TEXT,
  created_at TEXT NOT NULL DEFAULT (to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'))
);

CREATE INDEX agent_connections_agent_idx ON agent_connections (agent_id);

-- Private groups and membership ---------------------------------------------

CREATE TABLE groups (
  id TEXT PRIMARY KEY,
  name TEXT NOT NULL CHECK (length(trim(name)) > 0),
  creator_user_id TEXT NOT NULL REFERENCES users (id),
  created_at TEXT NOT NULL DEFAULT (to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'))
);

CREATE TABLE group_human_memberships (
  group_id TEXT NOT NULL REFERENCES groups (id) ON DELETE CASCADE,
  user_id TEXT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  role TEXT NOT NULL CHECK (role IN ('admin', 'member')),
  created_at TEXT NOT NULL DEFAULT (to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')),
  PRIMARY KEY (group_id, user_id)
);

CREATE INDEX group_human_memberships_user_idx ON group_human_memberships (user_id);

CREATE TABLE group_agent_memberships (
  group_id TEXT NOT NULL REFERENCES groups (id) ON DELETE CASCADE,
  agent_id TEXT NOT NULL REFERENCES agents (id) ON DELETE CASCADE,
  admitted_by_user_id TEXT NOT NULL REFERENCES users (id),
  created_at TEXT NOT NULL DEFAULT (to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')),
  PRIMARY KEY (group_id, agent_id)
);

CREATE INDEX group_agent_memberships_agent_idx ON group_agent_memberships (agent_id);

CREATE TABLE invitations (
  id TEXT PRIMARY KEY,
  token_hash TEXT NOT NULL UNIQUE,
  group_id TEXT NOT NULL REFERENCES groups (id) ON DELETE CASCADE,
  inviter_user_id TEXT NOT NULL REFERENCES users (id),
  expires_at TEXT NOT NULL,
  accepted_by_user_id TEXT REFERENCES users (id),
  accepted_at TEXT,
  created_at TEXT NOT NULL DEFAULT (to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'))
);

CREATE INDEX invitations_group_idx ON invitations (group_id);

-- Messages and send idempotency ---------------------------------------------

-- Authorship is exactly one human or one agent; never both and never neither.
CREATE TABLE messages (
  id TEXT PRIMARY KEY,
  group_id TEXT NOT NULL REFERENCES groups (id),
  author_kind TEXT NOT NULL CHECK (author_kind IN ('human', 'agent')),
  human_author_id TEXT REFERENCES users (id),
  agent_author_id TEXT REFERENCES agents (id),
  text TEXT NOT NULL CHECK (length(text) > 0),
  created_at TEXT NOT NULL DEFAULT (to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')),
  CHECK (
    (author_kind = 'human' AND human_author_id IS NOT NULL AND agent_author_id IS NULL)
    OR (author_kind = 'agent' AND agent_author_id IS NOT NULL AND human_author_id IS NULL)
  )
);

CREATE INDEX messages_group_created_idx ON messages (group_id, created_at, id);

CREATE TABLE message_idempotency (
  author_kind TEXT NOT NULL CHECK (author_kind IN ('human', 'agent')),
  human_author_id TEXT REFERENCES users (id),
  agent_author_id TEXT REFERENCES agents (id),
  idempotency_key TEXT NOT NULL CHECK (length(idempotency_key) > 0),
  request_digest TEXT NOT NULL,
  message_id TEXT NOT NULL REFERENCES messages (id) ON DELETE CASCADE,
  created_at TEXT NOT NULL DEFAULT (to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')),
  CHECK (
    (author_kind = 'human' AND human_author_id IS NOT NULL AND agent_author_id IS NULL)
    OR (author_kind = 'agent' AND agent_author_id IS NOT NULL AND human_author_id IS NULL)
  )
);

-- One key per effective author maps to exactly one message result.
CREATE UNIQUE INDEX message_idempotency_author_key_idx
  ON message_idempotency (
    author_kind,
    COALESCE(human_author_id, agent_author_id),
    idempotency_key
  );

-- Agent inbox -----------------------------------------------------------------

CREATE TABLE inbox_events (
  id TEXT PRIMARY KEY,
  agent_id TEXT NOT NULL REFERENCES agents (id) ON DELETE CASCADE,
  sequence INTEGER NOT NULL CHECK (sequence > 0),
  group_id TEXT NOT NULL REFERENCES groups (id),
  message_id TEXT NOT NULL REFERENCES messages (id) ON DELETE CASCADE,
  event_type TEXT NOT NULL DEFAULT 'message.created',
  created_at TEXT NOT NULL DEFAULT (to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')),
  acknowledged_at TEXT
);

-- Agent-local sequence is unique and allocated inside the send transaction.
CREATE UNIQUE INDEX inbox_events_agent_sequence_idx
  ON inbox_events (agent_id, sequence);

-- At most one event per agent, message, and event type.
CREATE UNIQUE INDEX inbox_events_agent_message_idx
  ON inbox_events (agent_id, message_id, event_type);

CREATE INDEX inbox_events_agent_pending_idx
  ON inbox_events (agent_id, sequence)
  WHERE acknowledged_at IS NULL;

-- OAuth grants and refresh tokens -------------------------------------------

CREATE TABLE oauth_grants (
  id TEXT PRIMARY KEY,
  oauth_client_id TEXT NOT NULL REFERENCES oauth_clients (client_id),
  kind TEXT NOT NULL CHECK (kind IN ('authorization_code', 'grant')),
  code_hash TEXT UNIQUE,
  subject_user_id TEXT REFERENCES users (id),
  agent_id TEXT REFERENCES agents (id) ON DELETE CASCADE,
  connection_id TEXT REFERENCES agent_connections (id) ON DELETE CASCADE,
  scopes TEXT NOT NULL,
  expires_at TEXT NOT NULL,
  consumed_at TEXT,
  created_at TEXT NOT NULL DEFAULT (to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'))
);

CREATE INDEX oauth_grants_client_idx ON oauth_grants (oauth_client_id);

-- Only token hashes are stored; rotation and revocation are recorded here.
CREATE TABLE oauth_refresh_tokens (
  id TEXT PRIMARY KEY,
  token_hash TEXT NOT NULL UNIQUE,
  connection_id TEXT NOT NULL REFERENCES agent_connections (id) ON DELETE CASCADE,
  family_id TEXT NOT NULL,
  expires_at TEXT NOT NULL,
  rotated_at TEXT,
  revoked_at TEXT,
  created_at TEXT NOT NULL DEFAULT (to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'))
);

CREATE INDEX oauth_refresh_tokens_family_idx ON oauth_refresh_tokens (family_id);

-- Bounded security audit -----------------------------------------------------

-- No credentials, tokens, session cookies, or message bodies belong here.
CREATE TABLE audit_events (
  id TEXT PRIMARY KEY,
  actor_kind TEXT NOT NULL CHECK (actor_kind IN ('human', 'agent', 'system')),
  actor_id TEXT,
  action TEXT NOT NULL,
  target_kind TEXT,
  target_id TEXT,
  outcome TEXT NOT NULL CHECK (outcome IN ('allowed', 'denied', 'failed')),
  metadata TEXT,
  created_at TEXT NOT NULL DEFAULT (to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'))
);

CREATE INDEX audit_events_created_idx ON audit_events (created_at);

-- 0003_oidc_artifacts
--
-- Storage for the in-process OAuth/OIDC authorization server.
--
-- The approved Program Design selects `oidc-provider` and forbids hand-rolling
-- the protocol. The library owns its own state model (Session, Interaction,
-- AuthorizationCode, AccessToken, RefreshToken, Grant, ReplayDetection, and the
-- rest) and persists it through a generic key-value adapter. Reimplementing that
-- contract across bespoke per-model tables would be exactly the hand-rolling the
-- design rejects, so provider-owned artifacts live in one generic table.
--
-- Ownership stays split and explicit:
--   oidc_artifacts        -> provider-owned protocol state, keyed by model and id
--   oauth_clients         -> the client registry the provider adapter mirrors
--   agent_connections     -> OUR authority: the row a revocation writes to
--   oauth_grants          -> reserved for S8 grant bookkeeping
--   oauth_refresh_tokens  -> reserved for S8 rotation-family revocation
--
-- A row carries its own expiry so an expired artifact is never returned, and
-- the index makes cleanup a bounded delete rather than a scan.

CREATE TABLE oidc_artifacts (
  model TEXT NOT NULL,
  id TEXT NOT NULL,
  payload TEXT NOT NULL,
  -- Null means the artifact has no expiry of its own (for example a client).
  expires_at TEXT,
  consumed_at TEXT,
  user_code TEXT,
  uid TEXT,
  grant_id TEXT,
  created_at TEXT NOT NULL DEFAULT (to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')),
  PRIMARY KEY (model, id)
);

-- Expiry sweeps and "is this artifact still alive" lookups.
CREATE INDEX oidc_artifacts_expiry_idx ON oidc_artifacts (model, expires_at);

-- The provider resolves a device or session by user code and by uid.
CREATE INDEX oidc_artifacts_user_code_idx ON oidc_artifacts (user_code)
  WHERE user_code IS NOT NULL;
CREATE INDEX oidc_artifacts_uid_idx ON oidc_artifacts (uid) WHERE uid IS NOT NULL;

-- Revoking a grant must reach every artifact that belongs to it.
CREATE INDEX oidc_artifacts_grant_idx ON oidc_artifacts (grant_id)
  WHERE grant_id IS NOT NULL;

